/**
 * Publication notes of the library ("00 - Library/Publication Summary/NNN - Year - Authors - Title.md",
 * `type: publication`).
 *
 *   readPublication(stem, text) → Paper | null   everything the tools need from one note (null: not a publication)
 *   citedByOf(papers)                             Map note name → sorted names of the library papers citing it
 *   libraryRoot(dir)                              the library's top folder, which holds PDFs/ and Library.bib
 *   isNoteName(name)                              "NNN - ….md", the name of a publication note
 *   section(body, name)                           text of "## <name>" up to the next "## " heading, one line
 *   bodyLinks(body)                               Set of [[link]] targets in the note body (alias and #heading removed)
 *   paperLabel(paper)                             "Ulrich 1995 (No. 005)"
 *
 * A Paper keeps the parsed properties (`props`) and the body, plus the fields derived from them:
 *   no          numeric library index (from `index`, else the first three characters of the name)
 *   index       the `index` property as written ("5"), or the note name when missing
 *   cite        authors as cited, from the file name ("Baldwin & Clark")
 *   status      the `status` property; a list is joined with ", "
 *   categories  concept maps linked in `category` (link targets)
 *   tags        lower-cased `tags`
 *   cites       every entry of `cites` as written: links to library notes, DOIs, OpenAlex ids, references as printed
 *               (generated by Scoping Review Workbench; Library Studio only reads it)
 *   refs        note names this paper cites: the links in `cites`, and in `references` / `references_pdf` of
 *               older vaults
 *   citedBy     note names of the library papers citing it: [] here, filled by openLibrary from citedByOf
 *   suggestedDoi, suggestedCategory, enrichedBy   proposals and provenance written by the enrich tool
 *   citekey     the `citekey` property ("" until the BibTeX export assigns one)
 *   links       Set of note names linked from the body
 *   abstract    the "Abstract" section
 *   why         `reason_for_importance`, else the "Why is this paper important (for my research)?" section
 * @module domain/publications
 */
import { linkTarget, splitNote, WIKILINK } from "./frontmatter.js";
import { compareCodePoints } from "./text-rules.js";

export const LIBRARY_DIR = "00 - Library/Publication Summary";
/** Older places of the publication notes, still recognised: the library folder itself, and its older name. */
export const LEGACY_LIBRARY_DIRS = Object.freeze(["00 - Library", "98 - Publications"]);
export const PDF_DIR = "00 - Library/PDFs";

const asList = v => (Array.isArray(v) ? v : v == null || v === "" ? [] : [v]);
const scalar = v => (Array.isArray(v) ? "" : String(v ?? ""));
const joined = (v, sep) => asList(v).map(String).filter(Boolean).join(sep);
/** Targets of the entries that are links ("[[Note]]"); DOIs, ids and plain text are left out. */
const linkTargets = v => asList(v).map(String).filter(s => new RegExp(`^${WIKILINK.source}$`).test(s.trim())).map(linkTarget);

export const libraryRoot = dir => String(dir).split("/")[0];
export const isNoteName = name => /^\d{3} - .*\.md$/.test(name);

/** @typedef {ReturnType<typeof readPublication>} Paper */

export function readPublication(stem, text) {
  const { props, body, raw } = splitNote(text);
  if (raw == null || props.type !== "publication") return null;
  const parts = stem.split(" - ");
  const index = scalar(props.index);
  const no = /^\d+$/.test(index) ? Number(index) : /^\d{3}/.test(stem) ? Number(stem.slice(0, 3)) : 0;
  return {
    stem, props, body, no,
    index: index || stem,
    title: scalar(props.title) || stem,
    year: scalar(props.year),
    authors: scalar(props.authors),
    cite: parts.length > 2 ? parts[2] : "",
    journal: scalar(props.journal),
    type: scalar(props.publication_type),
    class: scalar(props.publication_class),
    status: joined(props.status, ", "),
    importance: scalar(props.importance),
    doi: scalar(props.doi),
    citekey: scalar(props.citekey),
    pdf: linkTarget(scalar(props.pdf)),
    categories: asList(props.category).map(c => linkTarget(c)).filter(Boolean),
    tags: asList(props.tags).map(t => String(t).toLowerCase()),
    cites: asList(props.cites).map(String),
    refs: [...new Set([props.cites, props.references, props.references_pdf].flatMap(linkTargets))].filter(r => r !== stem),
    citedBy: [],
    suggestedDoi: scalar(props.suggested_doi),
    suggestedCategory: linkTarget(scalar(props.suggested_category)),
    enrichedBy: asList(props.enriched_by).map(String),
    links: bodyLinks(body),
    abstract: section(body, "Abstract"),
    why: joined(props.reason_for_importance, "; ") || section(body, "Why is this paper important(?: for my research)?\\?"),
  };
}

/** @param {Paper[]} papers @returns {Map<string, string[]>} every paper's name → the library papers whose refs name it */
export function citedByOf(papers) {
  const out = new Map(papers.map(p => [p.stem, []]));
  for (const p of papers) for (const r of p.refs) out.get(r)?.push(p.stem);
  for (const list of out.values()) list.sort(compareCodePoints);
  return out;
}

export function section(body, name) {
  const m = new RegExp(`^## ${name}[ \\t]*\\r?\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, "m").exec(body);
  return m ? m[1].replace(/\s+/g, " ").trim() : "";
}

export function bodyLinks(body) {
  const out = new Set();
  for (const m of String(body).matchAll(/\[\[([^\]]+)\]\]/g)) out.add(m[1].split("|")[0].split("#")[0].trim());
  return out;
}

export const paperLabel = p => `${p.cite} ${p.year} (No. ${String(p.no).padStart(3, "0")})`;

/**
 * What the co-citation tool writes into the vault besides the VOSviewer files: the evidence-synthesis note and its
 * figure (small multiples of the phase maps, SVG). Both describe the result only; the reading of the maps is
 * the researcher's, in another note.
 *
 *   GENERATED_MARK                                   the line in the note's front matter that marks it as generated
 *   perspectiveOrder(result)                         perspectives in display order: named ones as in the settings, then by size
 *   perspectiveName(p)                               the name given in the settings, else "Around <most-cited work>"
 *   SERIES, OTHER                                    the colours of the first three perspectives, and of the rest
 *   noteMarkdown(result, { name, today, figure, figurePath, vosDir, dataDir, download })
 *                                                    figure: the file name to embed; download: what was downloaded
 *   figureSvg(result, { name, today })               the phase maps side by side, two per row
 * @module domain/co-citation-notes
 */
import { fixed } from "./text-rules.js";

export const GENERATED_MARK = "generated-by: Library Studio (co-citation phases)";

/** Categorical slots 1–3 of the validated reference palette (light); a fourth perspective and later are "other". */
export const SERIES = ["#2a78d6", "#eb6834", "#1baf7a"];
export const OTHER = "#898781";

export const perspectiveName = p => p.name || `Around ${p.top}`;

export function perspectiveOrder(result) {
  return [...result.perspectives].sort((a, b) => a.slot - b.slot);
}

const thousands = n => String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
const pct = x => (x == null ? "—" : `${fixed(x * 100, 0)} %`);
const works = n => `${n} work${n === 1 ? "" : "s"}`;
const no = lib => `No. ${String(lib.no).padStart(3, "0")}`;
const cell = s => String(s).replace(/\|/g, "\\|");
const libLink = (lib, inTable = false) => `[[${lib.stem}${inTable ? "\\|" : "|"}${no(lib)}]]`;
/** "Ulrich 1995 ([[005 - …|No. 005]])", or the label alone for a work outside the library. */
const work = (n, inTable = false) => (n.lib ? `${n.label} (${libLink(n.lib, inTable)})` : n.label);

function mixText(result, mix) {
  const by = new Map(mix);
  return perspectiveOrder(result).filter(p => by.get(p.k)).map(p => `${by.get(p.k)} ${perspectiveName(p).toLowerCase()}`).join(", ");
}

export function noteMarkdown(result, { name, today, figure = "", figurePath = figure, vosDir = "", dataDir = "", download = null }) {
  const s = result.settings, sc = result.scopes, N = result.nodes, all = sc[0];
  const phases = sc.slice(1);
  const order = perspectiveOrder(result);
  const lines = [
    "---", "type: evidence-synthesis", GENERATED_MARK, `generated: ${today}`, "---", "",
    `# Co-citation phases: ${name}`, "",
    "> [!info] Generated by Library Studio (Co-citation phases). Rerunning the tool overwrites this note: write your reading of the maps in another note.",
    `> ${thousands(result.citing.total)} citing papers · ${all.nodes.length} works in the all-years map · ${all.clusters.length} clusters · density ${fixed(all.density, 3)}` +
      (phases.length ? ` · works per phase ${phases.map(p => p.nodes.length).join(" / ")}` : ""),
    "",
  ];
  if (figure) {
    lines.push(`![[${figure}]]`, "",
      `*Co-citation maps${phases.length ? " per phase" : ""}. Every work keeps its position in all panels: one VOS layout over all years. Colour shows the perspective (cluster of the all-years map) a work belongs to. Dot size shows its citations in that phase. Lines join pairs co-cited at least ${s.linkThreshold} times. A ring marks a work that is in the library. Grey dots are works shown only in other maps.*`, "");
  }

  // ---- data
  const q = download?.query ?? s.query;
  lines.push("## Data", "",
    `- **Search** (OpenAlex; title, abstract and keywords, without word stemming): \`${q || "not recorded"}\`` +
      (download ? "" : " (from the settings: the downloaded data has no record of the search it came from)"));
  if (download?.filter) lines.push(`- **OpenAlex filter:** \`${download.filter}\``);
  if (download?.date) lines.push(`- **Downloaded** on ${download.date}: ${thousands(download.works ?? 0)} works${download.complete === false ? " (**incomplete**: the download stopped before the last page)" : ""}.`);
  if (download?.differs) lines.push("- ⚠ The search in the settings has changed since this download. The data above is what was analysed; download again to use the new search.");
  lines.push(`- **Citing papers kept:** ${thousands(result.citing.total)}: published ${s.from}–${s.to}, with a reference list` +
    (s.coreOnly ? ", in OpenAlex's core sources" : "") + (s.subfields.length ? `, in ${s.subfields.length} subfields` : "") + ".");
  if (s.subfields.length) lines.push(`- **Subfields kept:** ${s.subfields.join("; ")}.`);
  lines.push("");

  // ---- method
  lines.push("## Method", "",
    "- **Co-citation.** A pair of works counts one co-citation for every citing paper that cites both. Counts are normalised by association strength (Van Eck & Waltman 2009).",
    `- **Thresholds.** A work enters the all-years map at ${s.overallThreshold} citations and a phase map at ${s.phaseThreshold}. Lines join pairs co-cited at least ${s.linkThreshold} times; density is the share of possible pairs that have a line.`,
    `- **Clusters.** VOSviewer's own clustering: the Constant Potts Model on association strength, resolution ${s.resolution}, run with the Leiden algorithm as the best of ${s.runs} runs.`,
    "- **Positions.** The VOS mapping method over all years, so a work keeps its place in every map.",
    phases.length ? `- **Phases** by the publication year of the citing papers: ${phases.map(p => `${p.phase} ${p.name}`).join(", ")}.` : "- **Phases:** none set; only the all-years map.",
    "- **Perspectives.** The clusters of the all-years map. A work that is only in a phase map belongs to the perspective it is co-cited with most.",
    "");

  // ---- cleaning
  const c = result.cleaning;
  lines.push("## Cleaning", "");
  lines.push(c.merged.length
    ? `- **Merged** (editions and duplicate records of one work): ${c.merged.map(g => `${g.label} (${g.members.length} records)`).join(", ")}.`
    : "- **Merged:** none.");
  const gone = c.dropped.filter(d => d.why === "not in OpenAlex"), cut = c.dropped.filter(d => d.why === "correction");
  if (gone.length) lines.push(`- **Dropped, no longer in OpenAlex** (deleted or merged records): ${gone.map(d => `${d.id} (cited ${d.cites} times)`).join(", ")}.`);
  if (cut.length) lines.push(`- **Dropped by correction:** ${cut.map(d => `${d.id}${d.title ? ` "${d.title}"` : ""} (cited ${d.cites} times)`).join(", ")}.`);
  if (c.missing.length) lines.push(`- ⚠ **Without metadata** (not looked up yet, so not shown): ${c.missing.map(m => `${m.id} (${m.cites})`).join(", ")}.`);
  if (s.corrections.trim()) lines.push("- **Corrections** (settings):", "", "```", s.corrections.trim(), "```");
  if (c.errors.length) lines.push(`- ⚠ **Corrections not understood:** ${c.errors.map(e => `line ${e.line} (${e.why})`).join("; ")}.`);
  lines.push("");

  // ---- the maps
  lines.push("## The maps", "", "| Map | Years | Citing papers | Average references | Works | Clusters | Lines | Density |", "|---|---|---:|---:|---:|---:|---:|---:|");
  for (const x of sc) lines.push(`| ${x.phase} | ${x.name} | ${thousands(x.citing)} | ${fixed(x.refsAvg, 1)} | ${x.nodes.length} | ${x.clusters.length} | ${thousands(x.links.length)} | ${fixed(x.density, 3)} |`);
  lines.push("");

  // ---- most-cited works
  const persp = new Map(result.perspectives.map(p => [p.k, perspectiveName(p)]));
  const top = [...all.nodes].sort((a, b) => N[b].cites[0] - N[a].cites[0] || a - b).slice(0, 10);
  lines.push("## Most-cited works", "", `| Work | Title | Citations | Perspective |`, "|---|---|---:|---|");
  for (const i of top) lines.push(`| ${work(N[i], true)} | ${cell(N[i].title)} | ${N[i].cites[0]} | ${cell(persp.get(N[i].persp) ?? "—")} |`);
  lines.push("");

  // ---- perspectives
  lines.push("## Perspectives", "", "The clusters of the all-years map. Name them in the tool's settings; the most-cited works of each:", "");
  for (const p of order) {
    const members = all.nodes.filter(i => N[i].persp === p.k).sort((a, b) => N[b].cites[0] - N[a].cites[0] || a - b);
    lines.push(`- **${perspectiveName(p)}** (${works(p.size)}): ${members.slice(0, 8).map(i => work(N[i])).join(", ")}.`);
  }
  lines.push("");

  // ---- phases
  if (phases.length) {
    lines.push("## What each phase shows", "");
    for (const x of phases) {
      lines.push(`### ${x.phase}, ${x.name}`, "", `${thousands(x.citing)} citing papers, ${works(x.nodes.length)}, ${x.clusters.length} clusters.`, "");
      x.clusters.forEach((cl, j) => lines.push(`- **Cluster ${j + 1}** (${works(cl.size)}: ${mixText(result, cl.mix)}): ${cl.top.map(i => work(N[i])).join(", ")}.`));
      lines.push("");
    }

    // ---- separation
    lines.push("## How separate the perspectives are", "",
      "Share of each perspective's co-citations (among the works of a phase map) that link it to another perspective. It depends partly on how many works a perspective has in a phase, so the trend says more than the level.", "",
      `| Perspective | ${phases.map(p => p.name).join(" | ")} |`, `|---|${"---:|".repeat(phases.length)}`);
    for (const p of order) lines.push(`| ${cell(perspectiveName(p))} | ${phases.map(x => pct(x.outShare[p.k])).join(" | ")} |`);
    lines.push("");
  }

  // ---- not in the library
  const shown = [...new Set(sc.flatMap(x => x.nodes))];
  const outside = [...all.nodes].filter(i => !N[i].lib).sort((a, b) => N[b].cites[0] - N[a].cites[0] || a - b);
  lines.push("## Often-cited works that are not in the library", "");
  if (outside.length) lines.push(`Works in the all-years map without a publication note, with their citations: ${outside.slice(0, 10).map(i => `${N[i].label}, "${N[i].title}" (${N[i].cites[0]})`).join("; ")}.`, "");
  lines.push(`In total, ${shown.filter(i => N[i].lib).length} of the ${shown.length} works in the maps are in the library, including ${all.nodes.filter(i => N[i].lib).length} of the ${all.nodes.length} in the all-years map.`, "");

  // ---- files
  lines.push("## Files", "");
  if (vosDir) lines.push(`- **VOSviewer files:** \`${vosDir}\`, one map file and one network file per map, with the shared positions and the clusters; the score column is the average citing year. In VOSviewer: Create → Create a map based on network data → choose a map file and its network file. The score gives the overlay view, which colours works by when they were cited.`);
  if (figure) lines.push(`- **Figure:** \`${figurePath}\`.`);
  if (dataDir) lines.push(`- **Downloaded data and settings:** \`${dataDir}\` (not in git; a rerun from it needs no OpenAlex credits).`);
  lines.push("");
  return lines.join("\n");
}

// ------------------------------------------------------------------ figure

const esc = s => String(s ?? "").replace(/[&<>"]/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[ch]));
const FONT = "Segoe UI, system-ui, Helvetica, Arial, sans-serif";
const INK = "#0b0b0b", INK2 = "#52514e", MUTED = "#898781", LINE = "#e1e0d9", SURFACE = "#fcfcfb", PANEL = "#ffffff";

export const colourOf = (result, k) => {
  const p = result.perspectives.find(x => x.k === k);
  return p && p.slot < SERIES.length ? SERIES[p.slot] : OTHER;
};

export function figureSvg(result, { name, today }) {
  const N = result.nodes, phases = result.scopes.length > 1 ? result.scopes.slice(1).map((x, j) => [x, j + 1]) : [[result.scopes[0], 0]];
  const cols = phases.length > 1 ? 2 : 1, rows = Math.ceil(phases.length / cols);
  const PW = 600, PH = 400, GAP = 24, TOP = 86, M = 24;
  const W = cols * PW + (cols - 1) * GAP + 2 * M, H = TOP + rows * PH + (rows - 1) * GAP + 40;
  const xs = N.map(n => n.x), ys = N.map(n => n.y);
  const X0 = Math.min(...xs), X1 = Math.max(...xs), Y0 = Math.min(...ys), Y1 = Math.max(...ys);
  const out = [`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="${FONT}">`,
    `<rect width="${W}" height="${H}" fill="${SURFACE}"/>`,
    `<text x="${M}" y="34" font-size="20" font-weight="600" fill="${INK}">${esc(`Co-citation maps: ${name}`)}</text>`];
  let lx = M;
  const legend = [...perspectiveOrder(result).filter(p => p.slot < SERIES.length).map(p => [SERIES[p.slot], perspectiveName(p)]),
    ...(result.perspectives.some(p => p.slot >= SERIES.length) ? [[OTHER, "Other perspectives"]] : [])];
  for (const [col, label] of legend) {
    out.push(`<circle cx="${lx + 6}" cy="58" r="6" fill="${col}"/><text x="${lx + 18}" y="63" font-size="14" fill="${INK2}">${esc(label)}</text>`);
    lx += 30 + label.length * 7.6;
  }
  out.push(`<circle cx="${lx + 6}" cy="58" r="6.5" fill="none" stroke="${INK}" stroke-width="1.4"/><text x="${lx + 18}" y="63" font-size="14" fill="${INK2}">in the library</text>`);
  phases.forEach(([sc, s], j) => {
    const ox = M + (j % cols) * (PW + GAP), oy = TOP + Math.floor(j / cols) * (PH + GAP);
    out.push(`<rect x="${ox}" y="${oy}" width="${PW}" height="${PH}" rx="10" fill="${PANEL}" stroke="${LINE}"/>`);
    out.push(`<text x="${ox + 14}" y="${oy + 24}" font-size="15" font-weight="600" fill="${INK}">${esc(`${sc.phase} ${sc.name}`)}</text>`);
    out.push(`<text x="${ox + 14}" y="${oy + 43}" font-size="12.5" fill="${INK2}">${esc(`${thousands(sc.citing)} citing papers · ${sc.nodes.length} works with ≥ ${sc.threshold} citations · ${sc.clusters.length} clusters`)}</text>`);
    const ix0 = ox + 18, iy0 = oy + 58, iw = PW - 36, ih = PH - 76;
    const k = Math.min(iw / ((X1 - X0) || 1), ih / ((Y1 - Y0) || 1));
    const bx = ix0 + (iw - k * (X1 - X0)) / 2, by = iy0 + (ih - k * (Y1 - Y0)) / 2;
    const pos = N.map(n => [bx + (n.x - X0) * k, by + (n.y - Y0) * k]);
    const nodes = new Set(sc.nodes);
    const mc = Math.max(1, ...sc.nodes.map(i => N[i].cites[s]));
    const r = new Map(sc.nodes.map(i => [i, 2.5 + 13 * Math.sqrt(N[i].cites[s] / mc)]));
    const lmax = Math.max(1, ...sc.links.map(l => l[2]));
    for (const [a, b, c] of sc.links) {
      const t = c / lmax;
      out.push(`<line x1="${fixed(pos[a][0], 1)}" y1="${fixed(pos[a][1], 1)}" x2="${fixed(pos[b][0], 1)}" y2="${fixed(pos[b][1], 1)}" stroke="${INK}" stroke-opacity="${fixed(0.06 + 0.4 * t, 3)}" stroke-width="${fixed(0.4 + 1.8 * t, 2)}"/>`);
    }
    N.forEach((n, i) => { if (!nodes.has(i)) out.push(`<circle cx="${fixed(pos[i][0], 1)}" cy="${fixed(pos[i][1], 1)}" r="1.8" fill="${MUTED}" fill-opacity="0.3"/>`); });
    for (const i of [...sc.nodes].sort((a, b) => N[a].cites[s] - N[b].cites[s] || a - b)) {
      out.push(`<circle cx="${fixed(pos[i][0], 1)}" cy="${fixed(pos[i][1], 1)}" r="${fixed(r.get(i), 1)}" fill="${colourOf(result, N[i].persp)}" stroke="${PANEL}" stroke-width="1.3"/>`);
      if (N[i].lib) out.push(`<circle cx="${fixed(pos[i][0], 1)}" cy="${fixed(pos[i][1], 1)}" r="${fixed(r.get(i) + 2.6, 1)}" fill="none" stroke="${INK}" stroke-width="1.1"/>`);
    }
    // labels of the most-cited works, where they fit without overlapping
    const boxes = [];
    let placed = 0;
    for (const i of [...sc.nodes].sort((a, b) => N[b].cites[s] - N[a].cites[s] || a - b)) {
      if (placed >= 9) break;
      const label = N[i].label, w = label.length * 6.6 + 6, [x, y] = pos[i], ri = r.get(i);
      for (const [tx, ty, anchor] of [[x + ri + 3, y + 4, "start"], [x - ri - 3, y + 4, "end"], [x, y - ri - 5, "middle"], [x, y + ri + 14, "middle"]]) {
        const x0 = anchor === "start" ? tx : anchor === "end" ? tx - w : tx - w / 2;
        const b = [x0, ty - 13, x0 + w, ty + 4];
        if (b[0] < ox + 4 || b[2] > ox + PW - 4 || b[1] < oy + 50 || b[3] > oy + PH - 4) continue;
        if (boxes.some(o => b[0] < o[2] && b[2] > o[0] && b[1] < o[3] && b[3] > o[1])) continue;
        boxes.push(b); placed++;
        out.push(`<text x="${fixed(tx, 1)}" y="${fixed(ty, 1)}" text-anchor="${anchor}" font-size="12" font-weight="500" fill="${INK}" stroke="${PANEL}" stroke-width="3" paint-order="stroke" stroke-linejoin="round">${esc(label)}</text>`);
        break;
      }
    }
  });
  out.push(`<text x="${M}" y="${H - 14}" font-size="12" fill="${MUTED}">${esc(`Same positions in every panel (VOS layout over ${result.scopes[0].name}). Dot size: citations in that map. Lines: pairs co-cited at least ${result.settings.linkThreshold} times. Grey dots: works shown only in other maps. Source: OpenAlex, ${today}.`)}</text>`);
  out.push("</svg>");
  return out.join("\n") + "\n";
}

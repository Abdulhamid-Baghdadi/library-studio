/**
 * What the cluster analysis writes into the vault, as text and data: one hub note per cluster, the report,
 * the "[auto]" graph presets, and the result the page shows. Pure: dates and ids are passed in.
 *
 *   GENERATED_MARKS            the property that marks a generated note (this app's, and the Python script's)
 *   hubName(c, terms)          "C01 - systems, graphs, communication"
 *   hubNotes(a, { today, hubNames })          → [{ name, text }]
 *   reportMarkdown(a, { today, hubNames })    → string
 *   updatePresets(data, a, { hubNames, hubDir, libraryDir, now, uuid })  → { data, added, removed }
 *   resultJson(a, { report })  → the result object for the page (metrics, clusters, map)
 *   palette(n)                 n distinct colours as 0xRRGGBB (golden-angle hues)
 * @module domain/cluster-notes
 */
import { SWEEP_FACTORS } from "./cluster-analysis.js";
import { LIBRARY_DIR } from "./publications.js";
import { fixed, general, percent, signed } from "./text-rules.js";

export const GENERATED_MARK = "generated-by: Library Studio (cluster discovery)";
export const GENERATED_MARKS = [GENERATED_MARK, "generated-by: 95 - Tools/Cluster discovery/cluster_discovery.py"];
export const AUTO_PREFIX = "[auto] ";
export const REPORT_NAME = "Cluster discovery report";

const pad2 = c => String(c).padStart(2, "0");
const mean = xs => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const byZ = (p, z) => [...p].sort((a, b) => z[b] - z[a] || a - b);

export function hubName(c, terms) {
  return `C${pad2(c)} - ${terms.slice(0, 3).join(", ")}`.replace(/[\\/:*?"<>|#^[\]]/g, "");
}

export const hubNames = a => a.parts.map((_, c) => hubName(c + 1, a.labels[c].terms));

/** Weight between every pair of clusters. */
function betweenClusters(a) {
  const between = new Map();
  for (const [u, v, w] of a.graph.edges()) {
    const cu = a.member[u], cv = a.member[v];
    if (cu === cv) continue;
    const key = `${Math.min(cu, cv)},${Math.max(cu, cv)}`;
    between.set(key, (between.get(key) || 0) + w);
  }
  return between;
}

export function hubNotes(a, { today, hubNames: names = hubNames(a) }) {
  const between = betweenClusters(a);
  return a.parts.map((p, c) => {
    const { terms, tags } = a.labels[c];
    const cats = new Map();
    for (const i of p) for (const cc of a.notes[i].categories) cats.set(cc, (cats.get(cc) || 0) + 1);
    const neigh = [...between].filter(([k]) => k.split(",").map(Number).includes(c))
      .map(([k, w]) => { const [x, y] = k.split(",").map(Number); return [w, x === c ? y : x]; })
      .sort((u, v) => v[0] - u[0] || v[1] - u[1]).slice(0, 3);
    const lines = [
      "---", "type: discovered-cluster", GENERATED_MARK, `generated: ${today}`,
      `cluster: C${pad2(c + 1)}`, `size: ${p.length}`,
      "terms:", ...terms.map(t => `  - ${t}`),
      "---", "",
      `# ${names[c]}`, "",
      "> [!info] Generated by Library Studio (cluster discovery) — deleted and recreated on every run.",
      `> Details and method: [[${REPORT_NAME}]]`, "",
      `- **Distinctive terms:** ${terms.join(", ")}`,
      `- **Shared tags:** ${tags.length ? tags.map(t => "#" + t).join(", ") : "—"}`,
      `- **Mean stability:** ${fixed(mean(p.map(i => a.stability[i])), 2)}`, "",
      "## Papers", "",
      "*Core papers first (highest within-cluster degree z); ⟷ = bridge paper.*", "",
    ];
    for (const i of byZ(p, a.z)) {
      const x = a.notes[i];
      lines.push(`- [[${x.stem}|${x.index} – ${x.title}]]` + (a.bridges.has(i) ? " ⟷" : ""));
    }
    lines.push("", "## Neighbouring clusters", "");
    lines.push(...(neigh.length ? neigh.map(([w, o]) => `- [[${names[o]}]] — link strength ${fixed(w, 2)}`) : ["- none"]));
    lines.push("", "## Overlap with concept maps", "");
    const sorted = [...cats].sort((u, v) => v[1] - u[1]);
    lines.push(...(sorted.length ? sorted.map(([k, v]) => `- ${k.split("- ").slice(1).join("- ") || k}: ${v}`) : ["- none — not covered by any concept map"]));
    return { name: names[c], text: lines.join("\n") + "\n" };
  });
}

export function reportMarkdown(a, { today, hubNames: names = null }) {
  const o = a.options, G = a.graph, parts = a.parts;
  const algo = o.algorithm[0].toUpperCase() + o.algorithm.slice(1);
  const lines = [
    "---", "type: evidence-synthesis", GENERATED_MARK, `generated: ${today}`, "---", "",
    "# Cluster discovery — publication library", "",
    "> [!info] Generated automatically — rerunning the analysis overwrites this note.",
    `> ${G.n} publication notes · ${G.edgeCount()} edges · ${parts.length} clusters · modularity **Q = ${fixed(a.Q, 3)}**`,
    `> Algorithm **${o.algorithm}**, quality **${o.quality}**, γ = ${general(o.gammaUsed)} · internally disconnected clusters: **${a.disconnected}**`,
    `> Parameters: mutual-kNN k = ${o.k}, weights text/tag/link = ${o.wText}/${o.wTag}/${o.wLink}, ${o.runs} ${algo} runs, consensus threshold ${o.threshold}`,
    "",
    "## How to read this", "",
    "- Clusters are found **without** using the `category` field, then compared with the concept maps below.",
    `- **Stability** = how often a paper landed with the rest of its cluster across all ${algo} runs (1.0 = always).`,
    "- **Bridge papers** have a high participation coefficient *P*: their connections are spread over several clusters.",
    "- Graph view: open the Graph Presets menu and pick an `[auto]` preset.",
    "",
    "## Agreement with the concept maps", "",
    `- NMI = **${fixed(a.nmi, 2)}**, ARI = **${fixed(a.ari, 2)}** against each paper's first \`category\` (1 = identical grouping, 0 = unrelated).`,
    "- A low value is not an error: it means the content suggests a different grouping than the concept maps.",
    "",
  ];
  const catNames = [...new Set(a.notes.flatMap(x => x.categories))].sort();
  const short = c => c.split("- ").slice(1).join("- ").split(" (")[0] || c;
  lines.push(`| Cluster | ${catNames.map(short).join(" | ")} | none |`);
  lines.push("|---|" + "---:|".repeat(catNames.length + 1));
  parts.forEach((p, c) => {
    const cnt = new Map();
    for (const i of p) for (const cc of (a.notes[i].categories.length ? a.notes[i].categories : ["none"])) cnt.set(cc, (cnt.get(cc) || 0) + 1);
    lines.push(`| C${pad2(c + 1)} | ${catNames.map(k => cnt.get(k) ?? "").join(" | ")} | ${cnt.get("none") ?? ""} |`);
  });
  lines.push("", "*Counts include every category of a paper, so rows can exceed the cluster size.*", "");

  parts.forEach((p, c) => {
    const { terms, tags } = a.labels[c];
    const cnt = new Map();
    for (const i of p) for (const cc of a.notes[i].categories) cnt.set(cc, (cnt.get(cc) || 0) + 1);
    const spread = [...cnt.values()].filter(v => v >= Math.max(2, 0.2 * p.length)).length;
    lines.push(`## C${pad2(c + 1)} — ${terms.slice(0, 3).join(", ")}`, "");
    if (names) lines.push(`- **Hub note:** [[${names[c]}]]`);
    lines.push(`- **Distinctive terms:** ${terms.join(", ")}`,
      `- **Shared tags:** ${tags.length ? tags.map(t => "#" + t).join(", ") : "—"}`,
      `- **Size:** ${p.length} papers · mean stability ${fixed(mean(p.map(i => a.stability[i])), 2)}` + (spread >= 3 ? " · ==spans several concept maps==" : ""),
      "", "| Paper | Year | P | z | Stability |", "|---|---|---:|---:|---:|");
    for (const i of byZ(p, a.z)) {
      const x = a.notes[i];
      lines.push(`| [[${x.stem}\\|${x.index} – ${[...x.title].slice(0, 70).join("")}]]${a.bridges.has(i) ? " ⟷" : ""} | ${x.year} | ${fixed(a.P[i], 2)} | ${signed(a.z[i], 2)} | ${fixed(a.stability[i], 2)} |`);
    }
    lines.push("");
  });

  lines.push("## Bridge papers", "",
    `Papers whose links are spread across clusters (P ≥ ${o.bridgeP}, Guimerà & Amaral connector range) or among the most central papers by betweenness. Candidates for cross-cutting research questions.`, "",
    "| Paper | Own cluster | P | Betweenness | Also connected to |", "|---|---|---:|---:|---|");
  for (const i of [...a.bridges].sort((u, v) => a.P[v] - a.P[u] || u - v)) {
    const nb = new Map();
    for (const [j, w] of a.graph.adj[i]) if (a.member[j] !== a.member[i]) nb.set(a.member[j], (nb.get(a.member[j]) || 0) + w);
    const top = [...nb].sort((u, v) => v[1] - u[1]).slice(0, 3).map(([k]) => `C${pad2(k + 1)}`);
    lines.push(`| [[${a.notes[i].stem}\\|${a.notes[i].index}]] | C${pad2(a.member[i] + 1)} | ${fixed(a.P[i], 2)} | ${fixed(a.B[i], 3)} | ${top.join(", ")} |`);
  }

  const { density, rows, robustness } = a.sweep;
  lines.push("", "## Robustness — CPM density sweep", "",
    "The Constant Potts Model (CPM) accepts a group as a community when its internal link density is above a threshold γ — independent of the size of the whole graph, so small tight groups are not merged away (no resolution limit). Sweeping γ upwards splits the library into ever denser cores.",
    `Overall graph density = ${general(density)}.`, "",
    "| γ (× density) | γ | Communities (≥2 papers) | Largest | Singletons | NMI vs main partition |", "|---:|---:|---:|---:|---:|---:|");
  for (const r of rows) lines.push(`| ${r.factor}× | ${general(r.gamma)} | ${r.communities} | ${r.largest} | ${r.singletons} | ${fixed(r.nmi, 2)} |`);
  lines.push("", "**Cluster robustness** — average share of a cluster that stays together in one CPM community across all γ values (1.0 = never splits):", "",
    "| Cluster | Robustness | Reading |", "|---|---:|---|");
  parts.forEach((p, c) => {
    const r = robustness[c];
    const reading = r >= 0.7 ? "robust — stays one group" : r >= 0.45 ? "splits into sub-cores at higher density" : "loose — mainly held together at coarse resolution";
    lines.push(`| C${pad2(c + 1)} — ${a.labels[c].terms.slice(0, 3).join(", ")} | ${percent(r)} | ${reading} |`);
  });
  lines.push("", "## Method", "",
    "1. **Graph** — nodes = publication notes; edges combine (a) TF-IDF cosine similarity of note text, kept only between mutual k-nearest neighbours, (b) shared tags weighted by inverse frequency, (c) explicit wikilinks between notes.",
    "2. **Communities** — Leiden algorithm (Traag, Waltman & van Eck, 2019; guarantees internally connected communities) optimising modularity with resolution γ (Reichardt & Bornholdt, 2006) or the Constant Potts Model; repeated with different random seeds and combined by consensus clustering (Lancichinetti & Fortunato, 2012). Louvain (Blondel et al., 2008) remains available for comparison.",
    `3. **Robustness** — CPM sweep over density thresholds (${SWEEP_FACTORS.join(", ")} × the graph density); clusters that survive many thresholds are robust.`,
    "4. **Quality** — Newman–Girvan modularity Q (Newman & Girvan, 2004); Q > 0.3 usually indicates clear community structure.",
    "5. **Roles** — participation coefficient P and within-module degree z (Guimerà & Amaral, 2005); betweenness centrality (Freeman, 1977).",
    "6. **Labels** — terms whose TF-IDF weight is highest in the cluster relative to the rest of the library.",
    "", "Same idea as DSM clustering in Pimmler & Eppinger 1994 (No. 028) and MacCormack Rusnak & Baldwin 2006 (No. 112): group elements so that most connections fall inside groups.", "");
  return lines.join("\n");
}

/** colorsys.hls_to_rgb(h, 0.55, 0.70) for golden-angle hues, as 0xRRGGBB. */
export function palette(n) {
  const v = (m1, m2, hue) => {
    hue = ((hue % 1) + 1) % 1;
    if (hue < 1 / 6) return m1 + (m2 - m1) * hue * 6;
    if (hue < 0.5) return m2;
    if (hue < 2 / 3) return m1 + (m2 - m1) * (2 / 3 - hue) * 6;
    return m1;
  };
  const l = 0.55, s = 0.7, m2 = l + s - l * s, m1 = 2 * l - m2;
  return Array.from({ length: n }, (_, i) => {
    const h = (i * 0.618033988749895) % 1;
    const [r, g, b] = [v(m1, m2, h + 1 / 3), v(m1, m2, h), v(m1, m2, h - 1 / 3)].map(x => Math.trunc(x * 255));
    return (r << 16) + (g << 8) + b;
  });
}

const pathQuery = paths => paths.map(p => `path:"${p}"`).join(" OR ");

/**
 * The graph-presets plugin file with the "[auto]" presets replaced. The user's own presets are kept; the
 * first of them lends its display options.
 */
export function updatePresets(data, a, { hubNames: names = hubNames(a), hubDir, libraryDir = LIBRARY_DIR, now, uuid }) {
  const presetsIn = Array.isArray(data?.presets) ? data.presets : [];
  const own = presetsIn.find(p => !String(p.name).startsWith(AUTO_PREFIX));
  const base = { ...(own?.options ?? {}) };
  delete base.search; delete base.colorGroups;
  Object.assign(base, { scale: 0.12, linkStrength: 0.25, centerStrength: 0.05 });

  const hubPaths = names.map(x => `${hubDir}/${x}.md`);
  const hubPrefix = a.parts.map((_, c) => `${hubDir}/C${pad2(c + 1)} - `);
  const cols = palette(a.parts.length);
  const RED = { a: 1, rgb: 0xe11d48 }, DARK = { a: 1, rgb: 0x475569 };
  const pubPath = i => a.notes[i].path;

  const positions = {};
  a.notes.forEach((x, i) => { positions[x.path] = a.pos[i]; });
  hubPaths.forEach((p, c) => { positions[p] = a.centres[c]; });
  const everything = `(path:"${libraryDir}" -file:"tags") OR path:"${hubDir}"`;
  const make = (name, search, groups, pos) => ({
    id: uuid(), name,
    options: { ...base, search, colorGroups: groups, showTags: false, showAttachments: false, showOrphans: true },
    nodePositions: Object.entries(pos).map(([id, [x, y]]) => ({ id, x, y })),
    createdAt: now, updatedAt: now,
  });

  const clusterGroups = a.parts.map((p, c) => ({ query: pathQuery([hubPrefix[c], ...p.map(pubPath)]), color: { a: 1, rgb: cols[c] } }));
  const bridges = [...a.bridges].sort((u, v) => u - v);
  const presets = [
    make(AUTO_PREFIX + "All clusters (hubs)", everything, clusterGroups, positions),
    make(AUTO_PREFIX + "Bridge papers", everything,
      [...(bridges.length ? [{ query: pathQuery(bridges.map(pubPath)), color: RED }] : []), { query: `path:"${hubDir}"`, color: DARK }], positions),
  ];
  a.parts.forEach((p, c) => {
    const members = p.map(pubPath);
    const sub = {};
    for (const i of p) sub[a.notes[i].path] = a.pos[i];
    sub[hubPaths[c]] = a.centres[c];
    const inBridges = p.filter(i => a.bridges.has(i)).map(pubPath);
    presets.push(make(`${AUTO_PREFIX}Cluster ${pad2(c + 1)} – ${a.labels[c].terms.slice(0, 3).join(", ")}`, pathQuery([hubPrefix[c], ...members]),
      [...(inBridges.length ? [{ query: pathQuery(inBridges), color: RED }] : []), { query: pathQuery([hubPrefix[c], ...members]), color: { a: 1, rgb: cols[c] } }], sub));
  });

  const old = presetsIn.filter(p => String(p.name).startsWith(AUTO_PREFIX));
  const out = { ...data, presets: [...presetsIn.filter(p => !String(p.name).startsWith(AUTO_PREFIX)), ...presets] };
  if (old.some(p => p.id === out.activePresetId)) out.activePresetId = null;
  return { data: out, added: presets.length, removed: old.length };
}

const r1 = x => Math.round(x * 10) / 10, r2 = x => Math.round(x * 100) / 100, r3 = x => Math.round(x * 1000) / 1000;

export function resultJson(a, { report }) {
  const o = a.options;
  return {
    notes: a.notes.length, edges: a.graph.edgeCount(), Q: r3(a.Q), nmi: r2(a.nmi), ari: r2(a.ari),
    gamma: o.gammaUsed, algorithm: o.algorithm, quality: o.quality, disconnected: a.disconnected,
    boilerplate: a.boiler.size, layers: a.layerCounts, report,
    clusters: a.parts.map((p, c) => ({
      id: `C${pad2(c + 1)}`, terms: a.labels[c].terms, size: p.length, robustness: r2(a.sweep.robustness[c]),
      papers: byZ(p, a.z).map(i => ({ id: a.notes[i].index, stem: a.notes[i].stem, title: a.notes[i].title })),
      bridges: p.filter(i => a.bridges.has(i)).map(i => a.notes[i].index),
    })),
    graph: {
      nodes: a.notes.map((x, i) => ({
        n: i, id: x.index, stem: x.stem, title: x.title, c: a.member[i], x: r1(a.pos[i][0]), y: r1(a.pos[i][1]),
        P: r2(a.P[i]), bridge: a.bridges.has(i), stability: r2(a.stability[i]), cat: a.cats[i],
      })),
      edges: a.graph.edges().map(([u, v, w]) => [u, v, r3(w)]),
    },
  };
}
